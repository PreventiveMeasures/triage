// The app's API as `who` asks it: GET, or POST of `body`.
function api(db, users) {
  const handler = createManagedRequestHandler({ config, db, originGate: { isOriginAllowed: () => true }, isShuttingDown: () => false, track() {} })
  return async (path, { who = 'admin', body } = {}) => {
    const session = users[who]
    const req = Object.assign(Readable.from(body ? [Buffer.from(JSON.stringify(body))] : []), { url: path, method: body ? 'POST' : 'GET',
      headers: { cookie: session.setCookie.split(';')[0], 'x-csrf-token': session.csrfToken } })
    // ServerResponse exposes Node's EventEmitter contract.
    // eslint-disable-next-line unicorn/prefer-event-target
    const res = Object.assign(new EventEmitter(), { status: 0, body: '', writeHead(status) { this.status = status }, end(value) { this.body = JSON.parse(value); this.writableEnded = true } })
    await handler(req, res)
    return res
  }
}

test('an admin sets a repository\'s review: whether it is enabled, how many reviews each version needs, and the commit it is reviewed since', async t => {
  const db = openSqliteManagedDb(':memory:')
  t.after(() => db.close())
  const send = api(db, await people(db))
  const path = '/api/admin/repositories/dependency-review'
  const setting = { repoId: 1, enabled: true, required: 3, since }
  assert.deepEqual((await send(path, { body: setting })).body, { ok: true, dependencyReview: { enabled: true, required: 3, since } })
  assert.deepEqual((await send('/api/admin/repositories?scope=connected')).body.repositories[0].dependencyReview, { enabled: true, required: 3, since })
  for (const bad of [{ required: 0 }, { required: 11 }, { required: 1.5 }, { since: 'abc' }, { since: since.toUpperCase() }, { enabled: 'yes' }, { repoId: '1' }]) {
    assert.equal((await send(path, { body: { ...setting, ...bad } })).status, 400, JSON.stringify(bad))
  }
  assert.equal((await send(path, { body: { ...setting, repoId: 999 } })).status, 404)
  assert.equal((await send(path, { who: 'alice', body: setting })).status, 403)
  assert.deepEqual((await send(path, { body: { repoId: 1, enabled: false, required: 1 } })).body.dependencyReview, { enabled: false, required: 1, since: null })
})

test('an open pull request\'s dependencies, asked with their review, tell each version\'s and what fails it; unasked, or where none is in effect, none', async t => {
  const db = openSqliteManagedDb(':memory:')
  t.after(() => db.close())
  const users = await people(db)
  const send = api(db, users)
  github(t, { compared: [{ filename: 'package-lock.json', status: 'modified' }], files: {
    [since]: BASELINE,
    [mergeBase]: { 'package-lock.json': npmLockfile({ ms: registry('ms', '2.1.2'), mine: gitDependency, kept: registry('kept', '1.0.0') }) },
    [head]: { 'package-lock.json': npmLockfile({ ms: registry('ms', '2.1.3'), mine: gitDependency, kept: registry('kept', '1.0.0'), 'left-pad': registry('left-pad', '1.3.0') }) },
  } })
  const ask = query => send(`/api/admin/repositories/pull-dependencies?${new URLSearchParams({ repoId: '1', number: '5', ...query })}`)
  assert.equal((await ask({ review: '1' })).body.review, undefined, 'not enabled')
  await db.setRepoDependencyReview(1, { enabled: true, required: 1, since })
  await publish(db, users.alice, context('ms', '2.1.3', '2.1.2'), ['one'])
  const answer = await ask({ review: '1' })
  assert.equal(answer.status, 200)
  assert.deepEqual(answer.body.review, { required: 1, since, canReview: true, unreviewed: 1, unsupported: 1 })
  assert.deepEqual(answer.body.lockfiles, [{ paths: ['package-lock.json'], more: 0, moreLocked: 0,
    added: [{ name: 'left-pad', version: '1.3.0', source: 'registry', baseline: true }, { name: 'ms', version: '2.1.3', source: 'registry', was: ['2.1.2'], reviews: 1 }],
    unreviewed: [{ name: 'kept', version: '1.0.0', source: 'registry', reviews: 0 }], moreUnreviewed: 0,
    unsupported: [{ name: 'mine', version: '1.0.0', source: 'git', from: 'git+ssh://github.com/org/mine.git', unsupported: 'git' }], moreUnsupported: 0 }],
  'ms passed against the version it was, left-pad locked at the commit reviewed since; kept, locked before, unreviewed; mine, from git there too, fails it')
  const plain = await ask({})
  assert.equal(plain.body.review, undefined)
  assert.deepEqual(plain.body.lockfiles[0].added.map(pkg => Object.keys(pkg).toSorted().join()), ['name,source,version', 'name,source,version,was'], 'unasked, what it adds alone')
  assert.equal((await ask({ review: '2' })).status, 400)
})
