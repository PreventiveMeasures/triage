// The app's API as `who` asks it: GET, or POST of `body`; with `more` of
// the server's assembly, its reviewed dependencies say.
function api(db, users, more = {}) {
  const handler = createManagedRequestHandler({ config, db, originGate: { isOriginAllowed: () => true }, isShuttingDown: () => false, track() {}, ...more })
  return async (path, { who = 'admin', body } = {}) => {
    const session = users[who]
    const req = Object.assign(Readable.from(body ? [Buffer.from(JSON.stringify(body))] : []), { url: path, method: body ? 'POST' : 'GET',
      headers: { cookie: session.setCookie.split(';')[0], 'x-csrf-token': session.csrfToken } })
    // ServerResponse exposes Node's EventEmitter contract.
    // eslint-disable-next-line unicorn/prefer-event-target
    const res = Object.assign(new EventEmitter(), { status: 0, body: '', writeHead(status) { this.status = status }, end(value) { this.body = JSON.parse(value); this.writableEnded = true } })
    await handler(req, res)
    return res
  }
}

