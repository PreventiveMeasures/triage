// A repository's dependency review as its open pull requests' lockfiles want
// it (server-managed/pull-dependency-reviews.ts,
// repository-dependency-reviews.ts): each version reviewed by its name,
// version and integrity, as npm's registry has it, by as many full,
// accepting, published reviews as required; one that can't be failing it; a
// file of the project's not reviewed; and those the repository's lockfiles
// locked at the commit it is reviewed since needing none.
