const config = { sessionCookieName: 'sid', cookieSecure: false, sessionTtlMs: 3_600_000 }
const publicMetadata = { id: 1, full_name: 'org/repo', private: false, visibility: 'public', default_branch: 'main' }
const [tip, head, mergeBase, since] = ['a', 'b', 'c', 'd'].map(char => char.repeat(40))

const sri = text => `sha512-${createHash('sha512').update(text).digest('base64')}`
const tgz = (name, version) => `https://registry.npmjs.org/${name}/-/${name.split('/').at(-1)}-${version}.tgz`
// npm's lockfile of `packages` by name, each the root's dependency.
const npmLockfile = packages => `${JSON.stringify({ name: 'app', version: '1.0.0', lockfileVersion: 3, requires: true, packages: {
  '': { name: 'app', version: '1.0.0', dependencies: Object.fromEntries(Object.entries(packages).map(([name, entry]) => [name, entry.version])) },
  ...Object.fromEntries(Object.entries(packages).map(([name, entry]) => [`node_modules/${name}`, entry])),
} }, null, 2)}\n`
const registry = (name, version, more = {}) => ({ version, resolved: tgz(name, version), integrity: sri(`${name}@${version}`), ...more })
const gitDependency = { version: '1.0.0', resolved: `git+ssh://git@github.com/org/mine.git#${'e'.repeat(40)}` }
const yarnLockfile = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


left-pad@^1.3.0:
  version "1.3.0"
  resolved "${tgz('left-pad', '1.3.0')}#${'5'.repeat(40)}"
  integrity ${sri('left-pad@1.3.0')}
`
const memory = () => {
  const kept = new Map()
  return { kept, read: key => Promise.resolve(kept.get(key) ?? null), write: (key, value) => { kept.set(key, value); return Promise.resolve() } }
}

test('read for its reviews, a version of npm\'s registry keeps its integrity; a link to its tarball with a query is another host\'s, and Yarn\'s link with no integrity keeps none', () => {
  const text = npmLockfile({ ms: registry('ms', '2.1.3'), q: registry('q', '1.5.1', { resolved: `${tgz('q', '1.5.1')}?cache=1` }) })
  assert.deepEqual(lockedPackages('npm', text, { integrities: true }), [
    { name: 'ms', version: '2.1.3', source: 'registry', integrity: sri('ms@2.1.3') },
    { name: 'q', version: '1.5.1', source: 'mirror', from: tgz('q', '1.5.1'), integrity: sri('q@1.5.1') },
  ])
  assert.deepEqual(lockedPackages('npm', text)[0], { name: 'ms', version: '2.1.3', source: 'registry' }, 'a scan\'s, none')
  const tarball = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n"left-pad@${tgz('left-pad', '1.3.0')}":
  version "1.3.0"\n  resolved "${tgz('left-pad', '1.3.0')}#${'5'.repeat(40)}"\n`
  assert.deepEqual(lockedPackages('yarn', tarball, { integrities: true }), [{ name: 'left-pad', version: '1.3.0', source: 'registry' }])
})

// A version as a lockfile locks it, of npm's registry with its integrity.
const at = (name, version, more = {}) => ({ name, version, source: 'registry', integrity: sri(`${name}@${version}`), ...more })
// A passing review of `pkg` by `reviewer`, compared with `base` of its own
// package where it is given.
const passing = (pkg, reviewer, base = null, more = {}) => ({ package: pkg.name, version: pkg.version, integrity: pkg.integrity,
  basePackage: base ? pkg.name : null, baseVersion: base, reviewer, ...more })
const strip = ({ integrity: _integrity, ...pkg }) => pkg
const bare = ({ was: _was, ...pkg }) => pkg

test('each version a pull request adds is told its review: how many pass it, of its integrity and compared with a version it was; that it needs none; or why it can\'t be reviewed, a file not reviewed', () => {
  const [ms, tool, kept] = [at('ms', '2.1.3', { was: ['2.1.2'] }), at('tool', '1.0.0', { dev: true }), at('kept', '1.0.0')]
  const mine = { name: 'mine', version: '1.0.0', source: 'git', from: 'git+ssh://github.com/org/mine.git' }
  const local = { name: 'local', version: '1.0.0', source: 'file' }
  const [other, reviewed] = [at('other', '1.0.0'), at('reviewed', '2.0.0')]
  const mirrored = { name: 'mirrored', version: '1.0.0', source: 'mirror', from: 'https://mirror.example/mirrored-1.0.0.tgz', integrity: sri('mirrored@1.0.0') }
  const loose = { name: 'loose', version: '1.0.0', source: 'registry' }
  const msElse = { ...bare(ms), integrity: sri('another ms') }
  const told = { base: mergeBase, head, cut: false, lockfiles: [
    { paths: ['package-lock.json'], more: 0, added: [ms, tool, kept, mine, local], moreLocked: 0,
      locked: [ms, tool, kept, mine, local, other, reviewed, mirrored, loose, msElse].map(bare) },
    { paths: ['berry/yarn.lock'], error: 'lockfile-unreadable', detail: 'a yarn.lock of Yarn 2 or later, which is not read' },
  ] }
  const state = { required: 2, since, canReview: true, reviews: [
    passing(ms, 'u1'), passing(ms, 'u2', '2.1.2'), passing(ms, 'u3', '2.0.0'),
    passing(tool, 'u1'), passing(tool, 'u1'), passing({ ...tool, integrity: sri('another tool') }, 'u2'),
    passing(reviewed, 'u1'), passing(reviewed, 'u2', '1.0.0'),
    passing(other, 'u1', null, { basePackage: 'elsewhere', baseVersion: '1.0.0' }),
    passing(mirrored, 'u1'), passing(mirrored, 'u2'),
  ] }
  const answer = reviewedDependencies(told, state, new Set([`kept@1.0.0\0${sri('kept@1.0.0')}`]))
  assert.deepEqual(answer.review, { required: 2, since, canReview: true, unreviewed: 2, unsupported: 3 })
  assert.deepEqual(answer.lockfiles[0], { paths: ['package-lock.json'], more: 0, moreLocked: 0,
    added: [{ ...strip(ms), reviews: 2 }, { ...strip(tool), reviews: 1 }, { ...strip(kept), baseline: true }, { ...mine, unsupported: 'git' }, local],
    unreviewed: [{ ...strip(other), reviews: 0 }, { ...strip(msElse), reviews: 0 }], moreUnreviewed: 0,
    unsupported: [{ ...mine, unsupported: 'git' }, { ...strip(mirrored), unsupported: 'tarball' }, { ...loose, unsupported: 'integrity' }], moreUnsupported: 0 },
  'ms passed by u1 whole and u2 against the version it was, not u3 against another; tool by u1 once, another integrity\'s not; kept locked at the commit reviews are counted since; ' +
  'git, a mirror\'s tarball and one with no integrity can\'t be reviewed; the same version locked with another integrity, unreviewed')
  assert.deepEqual(answer.lockfiles[1], told.lockfiles[1])
  assert.doesNotMatch(JSON.stringify(answer), /"integrity":|"locked":/u, 'neither integrities nor every version locked told')
  assert.deepEqual(reviewedPackages(told).toSorted(), ['kept', 'ms', 'ms', 'other', 'reviewed', 'tool'], 'the reviews of those reviewed asked alone')

  assert.equal(reviewedDependencies(told, state, null, 'github-not-found').review.baselineError, 'github-not-found')
  assert.deepEqual(reviewedDependencies(told, state, null).lockfiles[0].added[2], { ...strip(kept), reviews: 0 }, 'with no baseline, it wants its reviews')
  assert.deepEqual(reviewedDependencies(told, null, null), { ...told, lockfiles: [{ paths: ['package-lock.json'], more: 0, added: [strip(ms), strip(tool), strip(kept), mine, local] },
    told.lockfiles[1]] }, 'where none is in effect, what it adds alone')
})

test('of a directory\'s other versions wanting reviews and those that can\'t be reviewed, as many as MAX_UNREVIEWED are told, the rest counted, each once across directories; those past the versions read told', () => {
  const locked = [...Array.from({ length: MAX_UNREVIEWED + 2 }, (_, n) => at(`pkg-${n}`, '1.0.0')),
    ...Array.from({ length: MAX_UNREVIEWED + 1 }, (_, n) => ({ name: `git-${n}`, version: '1.0.0', source: 'git' }))]
  const dir = paths => ({ paths, more: 0, added: [], locked, moreLocked: 7 })
  const told = { base: mergeBase, head, cut: false, lockfiles: [dir(['a/package-lock.json']), dir(['b/package-lock.json'])] }
  const answer = reviewedDependencies(told, { required: 1, since: null, canReview: false, reviews: [] }, null)
  for (const one of answer.lockfiles) {
    assert.deepEqual([one.unreviewed.length, one.moreUnreviewed, one.unsupported.length, one.moreUnsupported, one.moreLocked], [MAX_UNREVIEWED, 2, MAX_UNREVIEWED, 1, 7])
  }
  assert.deepEqual([answer.review.unreviewed, answer.review.unsupported], [MAX_UNREVIEWED + 2, MAX_UNREVIEWED + 1], 'two workspaces locking the same versions count them once')
})

// Git's id of an object, as GitHub names a commit's trees and blobs.
const objectId = (type, body) => createHash('sha1').update(`${type} ${body.length}\0`).update(body).digest()
// The trees of `files` by path, as git hashes them: each by its id, with its
// entries; and the root's id.
function gitTrees(files) {
  const trees = new Map()
  const build = prefix => {
    const names = new Map()
    for (const path of Object.keys(files).filter(candidate => candidate.startsWith(prefix))) {
      const [name, ...rest] = path.slice(prefix.length).split('/')
      names.set(name, rest.length > 0)
    }
    const entries = [...names].map(([name, dir]) => dir ? { name, type: 'tree', mode: '40000', id: build(`${prefix}${name}/`) }
      : { name, type: 'blob', mode: '100644', id: objectId('blob', Buffer.from(files[prefix + name])) })
    const key = entry => entry.type === 'tree' ? `${entry.name}/` : entry.name
    entries.sort((a, b) => key(a) < key(b) ? -1 : 1)
    const id = objectId('tree', Buffer.concat(entries.flatMap(entry => [Buffer.from(`${entry.mode} ${entry.name}\0`), entry.id])))
    trees.set(id.toString('hex'), entries)
    return id
  }
  return { trees, root: build('').toString('hex') }
}
// GitHub's listing of a tree, as git/trees answers it with `recursive`.
function deepListing(trees, tree, prefix = '') {
  return trees.get(tree).flatMap(entry => entry.type === 'tree'
    ? [{ path: prefix + entry.name, mode: '040000', type: 'tree', sha: entry.id.toString('hex') }, ...deepListing(trees, entry.id.toString('hex'), `${prefix}${entry.name}/`)]
    : [{ path: prefix + entry.name, mode: entry.mode, type: 'blob', sha: entry.id.toString('hex') }])
}
// A file as GitHub's contents API answers it: its bytes, hashed to its blob.
function contents(path, text) {
  const bytes = Buffer.from(text)
  return { type: 'file', path, size: bytes.length, sha: objectId('blob', bytes).toString('hex'), encoding: 'base64', content: bytes.toString('base64') }
}

// GitHub, as a pull request's lockfiles and those at the commit reviews are
// counted since are read of it: pull request 5's base at `tip` and head at
// `head`, compared from `mergeBase`, changing `compared`; `files` by commit;
// `asked` what was asked of it.
function github(t, { files, compared = [] }) {
  const asked = []
  const commits = Object.fromEntries(Object.entries(files).map(([commit, tree]) => [commit, gitTrees(tree)]))
  t.mock.method(globalThis, 'fetch', input => {
    const url = new URL(typeof input === 'string' ? input : input.url)
    if (url.pathname === '/repos/org/repo') return Promise.resolve(Response.json(publicMetadata))
    asked.push(`${url.pathname}${url.search}`)
    if (url.pathname === '/repos/org/repo/pulls/5') return Promise.resolve(Response.json({ number: 5, base: { sha: tip, repo: { full_name: 'org/repo' } }, head: { sha: head } }))
    if (url.pathname === `/repos/org/repo/compare/${tip}...${head}`) return Promise.resolve(Response.json({ merge_base_commit: { sha: mergeBase }, files: compared }))
    const commit = /^\/repos\/org\/repo\/git\/commits\/([a-f\d]{40})$/u.exec(url.pathname)?.[1]
    if (commits[commit]) return Promise.resolve(Response.json({ sha: commit, tree: { sha: commits[commit].root } }))
    const tree = /^\/repos\/org\/repo\/git\/trees\/([a-f\d]{40})$/u.exec(url.pathname)?.[1]
    const listed = Object.values(commits).find(({ trees }) => trees.has(tree))
    if (listed) return Promise.resolve(Response.json({ sha: tree, tree: deepListing(listed.trees, tree), truncated: false }))
    const path = url.pathname.startsWith('/repos/org/repo/contents/') ? decodeURIComponent(url.pathname.slice('/repos/org/repo/contents/'.length)) : null
    const text = path && files[url.searchParams.get('ref')]?.[path]
    if (text) return Promise.resolve(Response.json(contents(path, text)))
    return Promise.resolve(Response.json({ message: 'Not Found' }, { status: 404 }))
  })
  return asked
}

const BASELINE = {
  'package-lock.json': npmLockfile({ ms: registry('ms', '2.1.2'), mine: gitDependency }),
  'web/yarn.lock': yarnLockfile,
  'src/index.js': 'export {}\n',
}

test('the versions the repository\'s lockfiles locked at the commit reviews are counted since are read once, of every lockfile there, those that can\'t be reviewed left out, and kept by the commit', async t => {
  const asked = github(t, { files: { [since]: BASELINE } })
  const kept = memory()
  const versions = await reviewBaseline('org/repo', 'token', 1, since, kept)
  assert.deepEqual([...versions].toSorted(), [`left-pad@1.3.0\0${sri('left-pad@1.3.0')}`, `ms@2.1.2\0${sri('ms@2.1.2')}`], 'a git dependency there needs its reviews all the same')
  assert.deepEqual(kept.kept.get(`1\0${since}`), [...versions])
  assert.ok(asked.includes(`/repos/org/repo/contents/web/yarn.lock?ref=${since}`))
  asked.length = 0
  assert.equal(await reviewBaseline('org/repo', 'token', 1, since, kept), versions)
  assert.deepEqual(asked, [], 'held in this instance')
  kept.kept.set(`2\0${since}`, [`x@1.0.0\0${sri('x@1.0.0')}`])
  assert.deepEqual([...await reviewBaseline('org/repo', 'token', 2, since, kept)], [`x@1.0.0\0${sri('x@1.0.0')}`])
  assert.deepEqual(asked, [], 'kept beyond it')
})

