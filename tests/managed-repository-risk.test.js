test('registry tarballs are told by their URL: npm’s, or a mirror’s by npm’s paths', () => {
  assert.deepEqual(registryTarball('https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz'), { name: 'left-pad', version: '1.3.0', mirror: false })
  assert.deepEqual(registryTarball('https://registry.yarnpkg.com/@babel/core/-/core-7.0.0-beta.1.tgz'), { name: '@babel/core', version: '7.0.0-beta.1', mirror: false })
  assert.deepEqual(registryTarball('https://registry.npmjs.org/@babel%2fcore/-/core-7.0.0.tgz'), { name: '@babel/core', version: '7.0.0', mirror: false })
  assert.deepEqual(registryTarball('https://npm.example.com/artifactory/api/npm/remote/@babel/core/-/core-7.0.0.tgz'), { name: '@babel/core', version: '7.0.0', mirror: true })
  // npm's own host with another path, or credentials, is no registry tarball of npm's.
  assert.equal(registryTarball('https://registry.npmjs.org/prefix/left-pad/-/left-pad-1.3.0.tgz'), null)
  assert.equal(registryTarball('https://user:token@registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz')?.mirror, true)
  assert.equal(registryTarball('https://registry.npmjs.org/left-pad/-/right-pad-1.3.0.tgz'), null)
  assert.equal(registryTarball('https://codeload.github.com/org/repo/tar.gz/abc'), null)
  assert.equal(registryTarball('file:../left-pad-1.3.0.tgz'), null)
})

test('lockfiles of npm, pnpm and Yarn 1 give their packages, each once, with where they come from', () => {
  assert.deepEqual(lockedPackages('npm', npmLockfile), [
    { name: 'left-pad', version: '1.3.0', source: 'registry' },
    { name: 'mine', version: '1.0.0', source: 'git', from: 'git+ssh://github.com/org/mine.git' },
    // Credentials in a URL are not shown.
    { name: 'mirrored', version: '2.0.0', source: 'mirror', from: 'https://npm.example.com/api/npm/remote/mirrored/-/mirrored-2.0.0.tgz', integrity: sri('mirrored') },
  ])
  assert.deepEqual(lockedPackages('pnpm', pnpmLockfile), [
    { name: 'is-number', version: '7.0.0', source: 'registry' },
    { name: 'left-pad', version: '1.3.0', source: 'registry' },
  ])
  // An alias is the package its tarball is.
  assert.deepEqual(lockedPackages('yarn', yarnLockfile), [
    { name: '@scope/thing', version: '1.0.0', source: 'registry' },
    { name: 'left-pad', version: '1.3.0', source: 'registry' },
  ])
  assert.throws(() => lockedPackages('yarn', '__metadata:\n  version: 8\n'), { name: 'LockfileError', message: /Yarn 2 or later/u })
  assert.throws(() => lockedPackages('npm', '{"lockfileVersion": 2}\n'), { name: 'LockfileError' })
  assert.throws(() => lockedPackages('bun', ''), TypeError)
})

test('a package’s risk is its most severe finding', () => {
  assert.equal(highestSeverity([]), null)
  assert.equal(highestSeverity([{ severity: 'high' }, { severity: 'critical' }, { severity: 'low' }]), 'critical')
})

// A scan's source of repositories and assessments, as the server's is, from
// what a test holds: `repos` by id, each `{ fullName, lockfiles, files }` or
// `{ fullName, error }`, and `assess` answering a package.
function sourceOf(repos, assess) {
  const opened = []
  return {
    opened,
    repos: () => Promise.resolve(Object.entries(repos).map(([id, repo]) => ({ repoId: Number(id), fullName: repo.fullName }))),
    async open({ repoId }) {
      await setImmediate()
      opened.push(repoId)
      const repo = repos[repoId]
      if (repo.error) throw new Error(repo.error)
      return { commit: 'a'.repeat(40), lockfiles: () => Promise.resolve(repo.lockfiles), file: path => Promise.resolve(repo.files[path]) }
    },
    assess,
  }
}

async function linesOf(lines) {
  const read = []
  for await (const line of lines) read.push(line)
  return read
}

test('a scan tells each repository’s lockfiles and packages, and each registry package’s risk once', async () => {
  const assessed = []
  const source = sourceOf({
    1: { fullName: 'org/one', lockfiles: [{ path: 'package-lock.json', format: 'npm' }, { path: 'web/bun.lock', format: 'bun' }, { path: 'Cargo.lock', format: 'cargo' }],
      files: { 'package-lock.json': npmLockfile } },
    2: { fullName: 'org/two', lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm' }, { path: 'old/package-lock.json', format: 'npm' }],
      files: { 'pnpm-lock.yaml': pnpmLockfile, 'old/package-lock.json': `${JSON.stringify({ name: 'old', lockfileVersion: 1, requires: true, dependencies: {} }, null, 2)}\n` } },
    3: { fullName: 'org/gone', error: 'no-repository' },
  }, async (pkg, signal) => {
    assert.equal(signal.aborted, false)
    assessed.push(pkg)
    await setImmediate()
    if (pkg.name === 'is-number') throw Object.assign(new Error('not there'), { code: 'package-not-found' })
    return { published: '2020-01-01T00:00:00.000Z', findings: pkg.name === 'left-pad'
      ? [{ id: 'deprecated', severity: 'critical', message: 'use padStart' }, { id: 'popularity', severity: 'high', tier: 30000 }] : [] }
  })
  const lines = await linesOf(repositoryRiskLines(source, new AbortController().signal))
  const of = type => lines.filter(line => line.type === type)
  assert.deepEqual(lines[0], { type: 'repos', repos: [{ id: 1, fullName: 'org/one' }, { id: 2, fullName: 'org/two' }, { id: 3, fullName: 'org/gone' }] })
  assert.deepEqual(lines.at(-1), { type: 'done' })
  assert.deepEqual(source.opened, [1, 2, 3], 'repositories are read one at a time, in turn')
  assert.deepEqual(of('repo'), [
    { type: 'repo', id: 1, commit: 'a'.repeat(40), lockfiles: [
      { path: 'package-lock.json', format: 'npm', npm: true }, { path: 'web/bun.lock', format: 'bun', npm: true }, { path: 'Cargo.lock', format: 'cargo', npm: false }] },
    { type: 'repo', id: 2, commit: 'a'.repeat(40), lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm', npm: true }, { path: 'old/package-lock.json', format: 'npm', npm: true }] },
    { type: 'repo', id: 3, error: 'no-repository' },
  ])
  const lockfiles = of('lockfile')
  assert.deepEqual(lockfiles.map(({ repo, path, packages, error }) => [repo, path, packages?.length ?? error]), [
    [1, 'package-lock.json', 3], [1, 'web/bun.lock', 'unsupported-format'], [2, 'pnpm-lock.yaml', 2], [2, 'old/package-lock.json', 'lockfile-unreadable'],
  ])
  assert.match(lockfiles[3].detail, /unsupported version/u)
  assert.equal(lockfiles[0].packages[2].integrity, undefined, 'a mirror’s integrity stays on the server')
  // left-pad is locked twice, assessed once; the git dependency not at all;
  // the mirror's held to its integrity.
  assert.deepEqual(assessed.map(pkg => pkg.name).toSorted(), ['is-number', 'left-pad', 'mirrored'])
  assert.deepEqual(assessed.find(pkg => pkg.name === 'mirrored'), { name: 'mirrored', version: '2.0.0', integrity: sri('mirrored') })
  assert.deepEqual(of('risk').toSorted((a, b) => a.name.localeCompare(b.name)), [
    { type: 'risk', name: 'is-number', version: '7.0.0', error: 'package-not-found' },
    { type: 'risk', name: 'left-pad', version: '1.3.0', published: '2020-01-01T00:00:00.000Z', severity: 'critical',
      findings: [{ id: 'deprecated', severity: 'critical' }, { id: 'popularity', severity: 'high' }] },
    { type: 'risk', name: 'mirrored', version: '2.0.0', published: '2020-01-01T00:00:00.000Z', severity: null, findings: [] },
  ])
})

test('an assessment refused as busy is asked again', async () => {
  let asked = 0
  const source = sourceOf({ 1: { fullName: 'org/one', lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm' }], files: { 'pnpm-lock.yaml': pnpmLockfile } } },
    ({ name }) => name === 'left-pad' && asked++ === 0 ? Promise.reject(new Error('npm-busy')) : Promise.resolve({ published: null, findings: [] }))
  const risks = (await linesOf(repositoryRiskLines(source, new AbortController().signal))).filter(line => line.type === 'risk')
  assert.equal(asked, 2)
  assert.deepEqual(risks.map(line => [line.name, line.error ?? line.severity]).toSorted(), [['is-number', null], ['left-pad', null]])
})

test('stopping a scan ends its lines at once and gives up the assessments under way', async () => {
  const signals = []
  const source = sourceOf({ 1: { fullName: 'org/one', lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm' }], files: { 'pnpm-lock.yaml': pnpmLockfile } } },
    (_pkg, signal) => new Promise((_resolve, reject) => {
      signals.push(signal)
      signal.addEventListener('abort', () => { reject(signal.reason) }, { once: true })
    }))
  const stop = new AbortController()
  const lines = repositoryRiskLines(source, stop.signal)
  const read = []
  for await (const line of lines) {
    read.push(line.type)
    if (line.type === 'lockfile') break
  }
  // The iterator returned: what was under way stops with it.
  await setImmediate()
  assert.deepEqual(read, ['repos', 'repo', 'lockfile'])
  assert.equal(signals.length, 2, 'two packages are assessed at a time')
  assert.ok(signals.every(signal => signal.aborted))

  // Stopped by the signal while waiting for the next line.
  const waiting = []
  const later = sourceOf({ 1: { fullName: 'org/one', lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm' }], files: { 'pnpm-lock.yaml': pnpmLockfile } } },
    (_pkg, signal) => new Promise((_resolve, reject) => {
      waiting.push(signal)
      signal.addEventListener('abort', () => { reject(signal.reason) }, { once: true })
    }))
  const controller = new AbortController()
  const stopped = repositoryRiskLines(later, controller.signal)
  const types = []
  const reading = (async () => { for await (const line of stopped) types.push(line.type) })()
  while (waiting.length < 2) await setImmediate()
  controller.abort()
  await reading
  assert.deepEqual(types, ['repos', 'repo', 'lockfile'])
  assert.ok(waiting.every(signal => signal.aborted))
})

