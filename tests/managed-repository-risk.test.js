const sri = text => `sha512-${createHash('sha512').update(text).digest('base64')}`
const sha1 = text => createHash('sha1').update(text).digest('hex')

const npmLockfile = `${JSON.stringify({
  name: 'app', version: '1.0.0', lockfileVersion: 3, requires: true,
  packages: {
    '': { name: 'app', version: '1.0.0', dependencies: { 'left-pad': '^1.3.0', mine: 'github:org/mine', mirrored: '^2.0.0' } },
    'node_modules/left-pad': { version: '1.3.0', resolved: 'https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz', integrity: sri('left-pad'), license: 'WTFPL' },
    'node_modules/mine': { version: '1.0.0', resolved: `git+ssh://git@github.com/org/mine.git#${'c'.repeat(40)}`, license: 'MIT' },
    'node_modules/mirrored': { version: '2.0.0', resolved: 'https://user:secret@npm.example.com/api/npm/remote/mirrored/-/mirrored-2.0.0.tgz', integrity: sri('mirrored'), license: 'MIT' },
  },
}, null, 2)}\n`

