test('a scan tells each repository’s lockfiles and packages, and each registry package’s risk once', async () => {
  const source = sourceOf({
    1: { fullName: 'org/one', lockfiles: [{ path: 'package-lock.json', format: 'npm' }, { path: 'web/bun.lock', format: 'bun' }, { path: 'Cargo.lock', format: 'cargo' }],
      files: { 'package-lock.json': npmLockfile } },
    2: { fullName: 'org/two', lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm' }, { path: 'old/package-lock.json', format: 'npm' }],
      files: { 'pnpm-lock.yaml': pnpmLockfile, 'old/package-lock.json': `${JSON.stringify({ name: 'old', lockfileVersion: 1, requires: true, dependencies: {} }, null, 2)}\n` } },
    3: { fullName: 'org/gone', error: 'no-repository' },
  }, async ({ name }, _teamScoped, signal) => {
    assert.equal(signal.aborted, false)
    await setImmediate()
    if (name === 'is-number') throw new NpmRiskError('package-not-found')
    return { published: '2020-01-01T00:00:00.000Z', findings: name === 'left-pad'
      ? [{ id: 'deprecated', severity: 'critical', message: 'use padStart' }, { id: 'popularity', severity: 'high', tier: 30000 }] : [],
    score: { score: name === 'left-pad' ? 60 : 0 } }
  })
  const lines = await Array.fromAsync(scan(source))
  const of = type => lines.filter(line => line.type === type)
  assert.deepEqual(lines[0], { type: 'repos', repos: [{ id: 1, fullName: 'org/one' }, { id: 2, fullName: 'org/two' }, { id: 3, fullName: 'org/gone' }] })
  assert.deepEqual(lines.at(-1), { type: 'done' })
  assert.deepEqual(source.opened, [1, 2, 3], 'repositories are opened in turn')
  assert.deepEqual(of('repo'), [
    { type: 'repo', id: 1, commit: 'a'.repeat(40), lockfiles: [{ path: 'package-lock.json', format: 'npm' }, { path: 'web/bun.lock', format: 'bun' }] },
    { type: 'repo', id: 2, commit: 'a'.repeat(40), lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm' }, { path: 'old/package-lock.json', format: 'npm' }] },
    { type: 'repo', id: 3, error: 'no-repository' },
  ])
  const lockfiles = of('lockfile')
  assert.deepEqual(lockfiles.map(({ repo, path, packages, error }) => [repo, path, packages?.length ?? error]), [
    [1, 'package-lock.json', 3], [1, 'web/bun.lock', 'unsupported-format'], [2, 'pnpm-lock.yaml', 2], [2, 'old/package-lock.json', 'lockfile-unreadable'],
  ])
  assert.match(lockfiles[3].detail, /unsupported version/u)
  // left-pad is locked twice, assessed once; the git dependency not at all;
  // the mirror's held to npm's integrity.
  assert.deepEqual(source.versions.toSorted(), ['is-number@7.0.0', 'left-pad@1.3.0', 'mirrored@2.0.0'])
  assert.deepEqual(risksOf(lines), [
    { type: 'risk', name: 'is-number', version: '7.0.0', error: 'package-not-found' },
    { type: 'risk', name: 'left-pad', version: '1.3.0', published: '2020-01-01T00:00:00.000Z', severity: 'critical', score: 60,
      findings: [{ id: 'deprecated', severity: 'critical' }, { id: 'popularity', severity: 'high' }] },
    { type: 'risk', name: 'mirrored', version: '2.0.0', integrity: sri('mirrored'), published: '2020-01-01T00:00:00.000Z', severity: null, score: 0, findings: [] },
  ])
})

