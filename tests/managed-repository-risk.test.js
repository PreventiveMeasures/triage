// A scan's source of repositories and assessments, as the server's is, from
// what a test holds: `repos` by id, each `{ fullName, lockfiles, files }`,
// or `{ fullName, error }` where it can't be opened, `{ fullName,
// lockfilesError }` where its lockfiles can't be listed and `revoked: true`
// where access to it is gone once they are read, and `paths` where a team's
// directories in it are; `assess` answering a version's document, npm's
// integrity of each package its own name's sri, but those npm has no
// document of (`gone`, by name and version, each risk's assessment of one
// npm removed, or null for none); and npm's `advisories` by package name,
// each row's `versions` those it covers, or none where `advisoriesFail`. Each lockfile's blob is its repository's id and its
// path. The packages a team lists the scope of are `scoped`; what was asked
// of GitHub and npm is noted, each advisories request's packages in
// `audited`.
function sourceOf(repos, assess, { advisories = {}, advisoriesFail = false, gone = {} } = {}) {
  const audited = [], listed = [], opened = [], read = [], scoped = new Set(), versions = []
  return {
    opened, listed, read, versions, scoped, audited,
    repos: () => Promise.resolve(Object.entries(repos).map(([id, repo]) => ({ repoId: Number(id), fullName: repo.fullName, ...repo.paths && { paths: repo.paths } }))),
    async open({ repoId }) {
      await setImmediate()
      opened.push(repoId)
      const repo = repos[repoId]
      if (repo.error) throw new GithubApiError(404, repo.error)
      return { commit: 'a'.repeat(40),
        file(path) { read.push(path); return Promise.resolve(repo.files[path]) },
        lockfiles() {
          listed.push(repoId)
          return repo.lockfilesError ? Promise.reject(new GithubApiError(429, repo.lockfilesError))
            : Promise.resolve(repo.lockfiles.map(lockfile => ({ sha: `${repoId}:${lockfile.path}`, ...lockfile })))
        },
        recheck: () => repo.revoked ? Promise.reject(new GithubApiError(404, 'no-repository')) : Promise.resolve() }
    },
    teamScoped: name => Promise.resolve(scoped.has(name)),
    version(name, version) {
      versions.push(`${name}@${version}`)
      if (`${name}@${version}` in gone) return Promise.reject(new NpmPackageError(404, 'package-not-found'))
      return Promise.resolve({ name, version, dist: { integrity: sri(name) } })
    },
    assess,
    removed(name, version) {
      const told = gone[`${name}@${version}`]
      return told ? Promise.resolve(told) : Promise.reject(new NpmRiskError('version-not-found', `npm has no ${name}@${version}`))
    },
    advisories(packages) {
      audited.push(packages)
      if (advisoriesFail) return Promise.reject(new NpmPackageError(502, 'upstream-unavailable'))
      return Promise.resolve(packages.flatMap(({ name, versions: asked }) => (advisories[name] ?? [])
        .map(row => ({ ecosystem: 'npm', source: 'registry', name, aliases: [], cwe: [], ...row, versions: row.versions.filter(version => asked.includes(version)) }))
        .filter(row => row.versions.length > 0)))
    },
  }
}

// A scan's lines, read with caches of its own unless given.
const scan = (source, signal = new AbortController().signal, caches = riskCaches()) => repositoryRiskLines(source, signal, caches)

const onePnpmRepo = { 1: { fullName: 'org/one', lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm' }], files: { 'pnpm-lock.yaml': pnpmLockfile } } }
const risksOf = lines => lines.filter(line => line.type === 'risk').toSorted((a, b) => a.name.localeCompare(b.name) || (a.integrity ?? '').localeCompare(b.integrity ?? ''))

test('a scan tells each repository’s lockfiles and packages, and each registry package’s risk once', async () => {
  const source = sourceOf({
    1: { fullName: 'org/one', lockfiles: [{ path: 'package-lock.json', format: 'npm' }, { path: 'web/bun.lock', format: 'bun' }, { path: 'Cargo.lock', format: 'cargo' }],
      files: { 'package-lock.json': npmLockfile } },
    2: { fullName: 'org/two', lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm' }, { path: 'old/package-lock.json', format: 'npm' }],
      files: { 'pnpm-lock.yaml': pnpmLockfile, 'old/package-lock.json': `${JSON.stringify({ name: 'old', lockfileVersion: 1, requires: true, dependencies: {} }, null, 2)}\n` } },
    3: { fullName: 'org/gone', error: 'no-repository' },
  }, async ({ name }, _teamScoped, signal) => {
    assert.equal(signal.aborted, false)
    await setImmediate()
    if (name === 'is-number') throw new NpmRiskError('package-not-found')
    return { published: '2020-01-01T00:00:00.000Z', findings: name === 'left-pad'
      ? [{ id: 'deprecated', severity: 'critical', message: 'use padStart' }, { id: 'popularity', severity: 'high', tier: 30000 }] : [] }
  })
  const lines = await Array.fromAsync(scan(source))
  const of = type => lines.filter(line => line.type === type)
  assert.deepEqual(lines[0], { type: 'repos', repos: [{ id: 1, fullName: 'org/one' }, { id: 2, fullName: 'org/two' }, { id: 3, fullName: 'org/gone' }] })
  assert.deepEqual(lines.at(-1), { type: 'done' })
  assert.deepEqual(source.opened, [1, 2, 3], 'repositories are read one at a time, in turn')
  assert.deepEqual(of('repo'), [
    { type: 'repo', id: 1, commit: 'a'.repeat(40), lockfiles: [{ path: 'package-lock.json', format: 'npm' }, { path: 'web/bun.lock', format: 'bun' }] },
    { type: 'repo', id: 2, commit: 'a'.repeat(40), lockfiles: [{ path: 'pnpm-lock.yaml', format: 'pnpm' }, { path: 'old/package-lock.json', format: 'npm' }] },
    { type: 'repo', id: 3, error: 'no-repository' },
  ])
  const lockfiles = of('lockfile')
  assert.deepEqual(lockfiles.map(({ repo, path, packages, error }) => [repo, path, packages?.length ?? error]), [
    [1, 'package-lock.json', 3], [1, 'web/bun.lock', 'unsupported-format'], [2, 'pnpm-lock.yaml', 2], [2, 'old/package-lock.json', 'lockfile-unreadable'],
  ])
  assert.match(lockfiles[3].detail, /unsupported version/u)
  // left-pad is locked twice, assessed once; the git dependency not at all;
  // the mirror's held to npm's integrity.
  assert.deepEqual(source.versions.toSorted(), ['is-number@7.0.0', 'left-pad@1.3.0', 'mirrored@2.0.0'])
  assert.deepEqual(risksOf(lines), [
    { type: 'risk', name: 'is-number', version: '7.0.0', error: 'package-not-found' },
    { type: 'risk', name: 'left-pad', version: '1.3.0', published: '2020-01-01T00:00:00.000Z', severity: 'critical',
      findings: [{ id: 'deprecated', severity: 'critical' }, { id: 'popularity', severity: 'high' }] },
    { type: 'risk', name: 'mirrored', version: '2.0.0', integrity: sri('mirrored'), published: '2020-01-01T00:00:00.000Z', severity: null, findings: [] },
  ])
})

