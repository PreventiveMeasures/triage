// A managed server over HTTP with one signed-in user of `role`, its answers
// read whole, Brotli-decoded where encoded.
async function server(t, role) {
  const config = { sessionCookieName: 'sid', cookieSecure: false, sessionTtlMs: 60_000 }
  const db = openSqliteManagedDb(':memory:')
  t.after(() => db.close())
  const session = await createSession(config, db, { githubUserId: 1, login: 'admin', name: null, avatarUrl: null }, Date.now())
  await db.setUserRole(session.userId, role)
  const handler = createManagedRequestHandler({ config, db, originGate: { isOriginAllowed: () => true }, isShuttingDown: () => false, track() {} })
  const http = createServer((req, res) => { void handler(req, res) })
  await new Promise(resolve => { http.listen(0, '127.0.0.1', resolve) })
  t.after(() => new Promise(resolve => { http.close(resolve) }))
  const cookie = session.setCookie.split(';')[0]
  return ({ method = 'GET', signedIn = true } = {}) => new Promise((resolve, reject) => {
    const req = request({ host: '127.0.0.1', port: http.address().port, path: '/api/admin/repositories/risk', method,
      headers: signedIn ? { cookie } : {} }, res => {
      const chunks = []
      res.on('data', chunk => chunks.push(chunk))
      res.on('end', () => {
        const body = Buffer.concat(chunks)
        resolve({ status: res.statusCode, headers: res.headers, text: (res.headers['content-encoding'] === 'br' ? brotliDecompressSync(body) : body).toString() })
      })
    })
    req.on('error', reject)
    req.end()
  })
}

test('repository risk is answered to admins alone, as lines', async t => {
  const ask = await server(t, 'admin')
  const answer = await ask()
  assert.equal(answer.status, 200)
  assert.equal(answer.headers['content-type'], 'application/x-ndjson')
  assert.deepEqual(answer.text.split('\n').filter(Boolean).map(line => JSON.parse(line)), [{ type: 'repos', repos: [] }, { type: 'done' }])
  assert.equal((await ask({ signedIn: false })).status, 401)
  assert.equal((await ask({ method: 'POST' })).status, 405)
  const manager = await server(t, 'manage')
  assert.equal((await manager()).status, 403)
})
