// A lockfile dropped in local or e2e mode is shown, never saved
// (ui/view/lockfile-drop.js): which of a drop's files make it, and the bundle
// of it alone the Code tab's pane takes.
import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import './_polyfills.js'

const { droppedLockfile, openDroppedLockfile, readDroppedLockfile } = await import('../ui/view/lockfile-drop.js')
const { beginViewNavigation } = await import('../ui/view/view-navigation.js')
const { viewedLockfile } = await import('../ui/view/lockfile-view.js')
const { bundleSourcesAsMap } = await import('../ui/view/bundle-sources.js')
const { state } = await import('../client/state.ts')

const nameOf = file => file.name.replace(/ \(\d+\)(?=\.[^.]*$)/u, '')
const file = (name, text = '') => new File([text], name)

describe('droppedLockfile', () => {
  it('shows the last lockfile of a drop, and takes every lockfile from the reports', () => {
    const first = file('package-lock.json'), last = file('pnpm-lock (2).yaml'), report = file('report.json')
    const dropped = droppedLockfile([first, report, last], nameOf)
    assert.equal(dropped.lockfile, last, 'a download\'s (2) left out of its name')
    assert.equal(dropped.manifest, null)
    assert.deepEqual([...dropped.taken], [first, last])
  })

  it('reads a yarn.lock with the package.json dropped beside it, and leaves one beside another lockfile to the reports', () => {
    const lock = file('yarn.lock'), manifest = file('package.json')
    assert.deepEqual(droppedLockfile([manifest, lock], nameOf), { lockfile: lock, manifest, taken: new Set([lock, manifest]) })
    const pnpm = file('pnpm-lock.yaml')
    assert.deepEqual(droppedLockfile([pnpm, manifest], nameOf), { lockfile: pnpm, manifest: null, taken: new Set([pnpm]) })
  })

  it('names lockfiles by their names alone, as the code viewer does', () => {
    assert.equal(droppedLockfile([file('report.json'), file('package.json'), file('my-lock.yaml'), file('yarn.lock.bak')], nameOf), null)
    assert.ok(droppedLockfile([file('npm-shrinkwrap.json')], nameOf))
    assert.ok(droppedLockfile([file('pnpm-lock.feature.yaml')], nameOf), 'a git branch\'s pnpm lockfile')
  })
})

describe('readDroppedLockfile', () => {
  it('makes a bundle of it alone, a new one for each drop', async () => {
    const lock = file('pnpm-lock (1).yaml', 'lockfileVersion: \'9.0\'\n')
    const one = await readDroppedLockfile({ lockfile: lock, manifest: null }, nameOf)
    const two = await readDroppedLockfile({ lockfile: lock, manifest: null }, nameOf)
    assert.equal(one.name, 'pnpm-lock.yaml')
    assert.equal(one.details.kind, 'sourcemap')
    assert.deepEqual([...bundleSourcesAsMap(one.details)], [['pnpm-lock.yaml', 'lockfileVersion: \'9.0\'\n']])
    assert.notEqual(one.details.integrity, two.details.integrity, 'what was read for one drop is not taken for another\'s')
  })

  it('holds the package.json a yarn.lock names its project\'s importers by', async t => {
    t.after(() => { state.bundleSourceLockfile = false })
    const yarnLock = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n'
      + 'ms@^2.0.0:\n  version "2.1.3"\n  resolved "https://registry.yarnpkg.com/ms/-/ms-2.1.3.tgz#574c8138ce1d2b5861f0b44579dbadd60c6615b2"\n'
      + '  integrity sha512-6FlzubTLZG3J2a/NVCAleEhjzq5oxgHyaCU9yYXvcLsvoVaHJq/s5xXI6/XXP6tz7R9xAOtHnSO/tXtF3WRTlA==\n'
    const dropped = await readDroppedLockfile({ lockfile: file('yarn.lock', yarnLock),
      manifest: file('package.json', JSON.stringify({ name: 'app', version: '1.2.3', dependencies: { ms: '^2.0.0' } })) }, nameOf)
    state.bundleSourceLockfile = true
    const { details, name } = dropped
    const read = await new Promise(resolve => {
      const pending = viewedLockfile(details, name, bundleSourcesAsMap(details).get(name), bundleSourcesAsMap(details), () => resolve(pending))
    })
    assert.equal(read.status, 'ready', read.message)
    assert.deepEqual(read.lockfile.importers['.'], { version: '1.2.3', dependencies: ['ms@^2.0.0'] })
  })
})

describe('openDroppedLockfile', () => {
  // A dropped file whose read ends when the test says.
  const slow = name => {
    let done
    const read = new Promise(resolve => { done = resolve })
    return { lockfile: { name, size: 1, text: () => read }, manifest: null, end: (text = '{}\n') => done(text) }
  }
  const failing = name => ({ lockfile: { name, size: 1, text: () => Promise.reject(new Error('gone')) }, manifest: null })

  it('shows the lockfile read, unless the page went elsewhere meanwhile', async () => {
    const failed = [], shown = []
    const fail = err => { failed.push(err.message) }, show = lockfile => { shown.push(lockfile.name) }
    const kept = slow('package-lock.json')
    const opened = openDroppedLockfile(kept, nameOf, show, fail)
    kept.end()
    assert.equal(await opened, true)
    assert.deepEqual(shown, ['package-lock.json'])
    const left = slow('pnpm-lock.yaml')
    const leaving = openDroppedLockfile(left, nameOf, show, fail)
    beginViewNavigation()
    left.end()
    assert.equal(await leaving, false, 'Home or the sidebar keeps the screen')
    assert.deepEqual(shown, ['package-lock.json'])
    const unread = openDroppedLockfile(failing('yarn.lock'), nameOf, show, fail)
    beginViewNavigation()
    assert.equal(await unread, false)
    assert.deepEqual(failed, [], 'nor tells of a read it no longer waits for')
    assert.equal(await openDroppedLockfile(failing('yarn.lock'), nameOf, show, fail), false)
    assert.deepEqual(failed, ['gone'])
  })

  it('shows the later of two drops, whichever read ends first', async () => {
    const shown = []
    const show = lockfile => { shown.push(lockfile.name) }
    const earlier = slow('package-lock.json'), later = slow('pnpm-lock.yaml')
    const first = openDroppedLockfile(earlier, nameOf, show, () => {})
    const second = openDroppedLockfile(later, nameOf, show, () => {})
    later.end()
    assert.equal(await second, true)
    earlier.end()
    assert.equal(await first, false)
    assert.deepEqual(shown, ['pnpm-lock.yaml'])
  })
})
