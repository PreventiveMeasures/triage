// The packages a pull request's lockfiles add (server-managed/pull-dependencies.ts):
// read of its merge base and its head where it changes a lockfile of npm's
// ecosystem, a package new to a directory one none of its lockfiles locked.
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { test } from 'node:test'
import { openSqliteManagedDb } from '../server-managed/db.ts'
import { createManagedRequestHandler } from '../server-managed/http.ts'
import { MAX_ADDED, MAX_DIRECTORIES, lockfileFormat, pullDependencies, touchesLockfile } from '../server-managed/pull-dependencies.ts'
import { createSession } from '../server-managed/session.ts'

const config = { sessionCookieName: 'sid', cookieSecure: false, sessionTtlMs: 60_000 }
const repo = { repoId: 1, fullName: 'org/repo', private: false, installationId: null, defaultBranch: 'main', htmlUrl: '', addedBy: null }
const publicMetadata = { id: 1, full_name: 'org/repo', private: false, visibility: 'public', default_branch: 'main' }
const [tip, head, mergeBase] = ['a', 'b', 'c'].map(char => char.repeat(40))
// Commits of their own, for a test whose lockfiles differ from another's at
// the same paths, as each is read once an instance by its commit.
let commits = 0
const fresh = () => {
  commits++
  return { headAt: commits.toString(16).padStart(40, 'e'), baseAt: commits.toString(16).padStart(40, 'f') }
}

const tgz = (name, version) => `https://registry.npmjs.org/${name}/-/${name.split('/').at(-1)}-${version}.tgz`
const sri = text => `sha512-${createHash('sha512').update(text).digest('base64')}`
// npm's lockfile of `packages` by their paths under node_modules, each led
// to by the one it is installed in, the root's a devDependency where it is dev.
function npmLockfile(packages) {
  const entries = Object.fromEntries(Object.entries(packages).map(([path, entry]) => [`node_modules/${path}`, { ...entry }]))
  const root = { name: 'app', version: '1.0.0' }
  for (const [path, entry] of Object.entries(entries)) {
    const at = path.lastIndexOf('/node_modules/')
    const parent = at === -1 ? root : entries[path.slice(0, at)]
    const name = path.slice(at === -1 ? 'node_modules/'.length : at + '/node_modules/'.length)
    const field = parent === root && entry.dev ? 'devDependencies' : 'dependencies'
    parent[field] = { ...parent[field], [name]: entry.version }
  }
  return `${JSON.stringify({ name: 'app', version: '1.0.0', lockfileVersion: 3, requires: true, packages: { '': root, ...entries } }, null, 2)}\n`
}
const registry = (name, version, more = {}) => ({ version, resolved: tgz(name, version), integrity: sri(`${name}@${version}`), ...more })
const yarnLockfile = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


left-pad@^1.3.0:
  version "1.3.0"
  resolved "${tgz('left-pad', '1.3.0')}"
  integrity ${sri('left-pad')}
`
const pnpmLockfile = `lockfileVersion: '9.0'

importers:

  .:
    dependencies:
      is-number:
        specifier: ^7.0.0
        version: 7.0.0
      left-pad:
        specifier: ^1.3.0
        version: 1.3.0

packages:

  is-number@7.0.0:
    resolution: {integrity: ${sri('is-number')}}

  left-pad@1.3.0:
    resolution: {integrity: ${sri('left-pad')}}

snapshots:

  is-number@7.0.0: {}

  left-pad@1.3.0: {}
`

// The root's lockfile bumps ms, adds a dev-only tool, a dependency it pulls
// in and a git one; web/ moves from Yarn's lockfile to pnpm's; new/ is a
// new package's, every package of it new; gone/'s is removed; berry/'s is a
// later Yarn's; and a test's fixture and a node_modules' none.
const FILES = {
  [mergeBase]: {
    'package-lock.json': npmLockfile({ ms: registry('ms', '2.1.2') }),
    'web/yarn.lock': yarnLockfile,
    'gone/package-lock.json': npmLockfile({ ms: registry('ms', '2.1.3') }),
    'berry/yarn.lock': '__metadata:\n  version: 8\n',
  },
  [head]: {
    'package-lock.json': npmLockfile({
      ms: registry('ms', '2.1.3'), tool: registry('tool', '1.0.0', { dev: true }), 'tool/node_modules/plain-crypto-js': registry('plain-crypto-js', '4.2.1', { dev: true }),
      mine: { version: '1.0.0', resolved: `git+ssh://git@github.com/org/mine.git#${'d'.repeat(40)}` },
    }),
    'web/pnpm-lock.yaml': pnpmLockfile,
    'new/package-lock.json': npmLockfile({ 'left-pad': registry('left-pad', '1.3.0') }),
    'berry/yarn.lock': '__metadata:\n  version: 8\n\n"left-pad@npm:^1.3.0":\n  version: 1.3.0\n',
  },
}
const [FILES_HEAD, FILES_BASE] = [head, mergeBase]
const COMPARED = [
  { filename: 'README.md', status: 'modified' }, { filename: 'package-lock.json', status: 'modified' }, { filename: 'package.json', status: 'modified' },
  { filename: 'web/pnpm-lock.yaml', status: 'added' }, { filename: 'web/yarn.lock', status: 'removed' }, { filename: 'new/package-lock.json', status: 'added' },
  { filename: 'gone/package-lock.json', status: 'removed' }, { filename: 'berry/yarn.lock', status: 'modified' },
  { filename: 'test/fixtures/app/package-lock.json', status: 'added' }, { filename: 'vendor/node_modules/x/package-lock.json', status: 'added' },
]

// A file as GitHub's contents API answers it: its bytes, hashed to its blob.
function contents(path, text) {
  const bytes = Buffer.from(text)
  const sha = createHash('sha1').update(`blob ${bytes.length}\0`).update(bytes).digest('hex')
  return { type: 'file', path, size: bytes.length, sha, encoding: 'base64', content: bytes.toString('base64') }
}

// GitHub, as the pull request's lockfiles are read of it: pull request 5's
// base at `tip` and head at `head`, compared from `mergeBase`; `asked` what
// was asked of it, and `compared` the files GitHub's comparison lists.
function github(t, { compared = COMPARED, files = FILES, pullFiles = null, headAt = FILES_HEAD, baseAt = FILES_BASE } = {}) {
  const asked = []
  t.mock.method(globalThis, 'fetch', input => {
    const url = new URL(typeof input === 'string' ? input : input.url)
    const at = `${url.pathname}${url.search}`
    if (url.pathname === '/repos/org/repo') return Promise.resolve(Response.json(publicMetadata))
    asked.push(at)
    if (url.pathname === '/repos/org/repo/pulls/5') return Promise.resolve(Response.json({ number: 5, base: { sha: tip, repo: { full_name: 'org/repo' } }, head: { sha: headAt } }))
    if (url.pathname === `/repos/org/repo/compare/${tip}...${headAt}`) {
      return Promise.resolve(Response.json({ merge_base_commit: { sha: baseAt }, files: compared }))
    }
    if (url.pathname === '/repos/org/repo/pulls/5/files' && pullFiles) {
      const page = Number(url.searchParams.get('page'))
      return Promise.resolve(Response.json(pullFiles.slice((page - 1) * 100, page * 100)))
    }
    const path = url.pathname.startsWith('/repos/org/repo/contents/') ? decodeURIComponent(url.pathname.slice('/repos/org/repo/contents/'.length)) : null
    const text = path && files[url.searchParams.get('ref')]?.[path]
    if (text) return Promise.resolve(Response.json(contents(path, text)))
    return Promise.resolve(Response.json({ message: 'Not Found' }, { status: 404 }))
  })
  return asked
}

const memory = () => {
  const kept = new Map()
  return { kept, read: key => Promise.resolve(kept.get(key) ?? null), write: (key, value) => { kept.set(key, value); return Promise.resolve() } }
}

test('the lockfiles read are npm\'s, pnpm\'s and Yarn\'s, by name, none under a node_modules nor a test\'s fixtures', () => {
  assert.deepEqual(['package-lock.json', 'a/npm-shrinkwrap.json', 'pnpm-lock.yaml', 'pnpm-lock.feature.yaml', 'b/yarn.lock', 'bun.lock', 'Cargo.lock', 'package.json',
    'node_modules/x/package-lock.json', 'test/fixtures/app/yarn.lock', 'fixtures/yarn.lock', 'my-yarn.lock'].map(lockfileFormat),
  ['npm', 'npm', 'pnpm', 'pnpm', 'yarn', null, null, null, null, null, 'yarn', null], 'fixtures outside a test directory are a project\'s')
  assert.equal(touchesLockfile(['src/a.js', 'pnpm-lock.yaml'], 2), true)
  assert.equal(touchesLockfile(['src/a.js'], 1), false)
  assert.equal(touchesLockfile(['src/a.js'], 101), null, 'none among those listed, of more: it may')
})

test('a pull request\'s new packages are those its head\'s lockfiles lock that none of its directory\'s did at its merge base, whichever version', async t => {
  const asked = github(t)
  const kept = memory()
  const told = await pullDependencies('org/repo', 'token', 5, kept)
  assert.equal(told.base, mergeBase, 'compared from where its branch left its base, not its base\'s tip')
  assert.equal(told.head, head)
  assert.equal(told.cut, false)
  assert.deepEqual(told.lockfiles, [
    { paths: ['package-lock.json'], more: 0, added: [
      { name: 'mine', version: '1.0.0', source: 'git', from: 'git+ssh://github.com/org/mine.git' },
      { name: 'plain-crypto-js', version: '4.2.1', source: 'registry', dev: true },
      { name: 'tool', version: '1.0.0', source: 'registry', dev: true },
    ] },
    { paths: ['berry/yarn.lock'], error: 'lockfile-unreadable', detail: 'a yarn.lock of Yarn 2 or later, which is not read' },
    { paths: ['gone/package-lock.json'], added: [], more: 0 },
    { paths: ['new/package-lock.json'], added: [{ name: 'left-pad', version: '1.3.0', source: 'registry' }], more: 0 },
    { paths: ['web/pnpm-lock.yaml', 'web/yarn.lock'], added: [{ name: 'is-number', version: '7.0.0', source: 'registry' }], more: 0 },
  ], 'ms bumped none; Yarn\'s lockfile replaced by pnpm\'s, left-pad none; no integrity told')
  const reads = asked.filter(at => at.includes('/contents/'))
  assert.ok(!reads.some(at => /fixtures|node_modules/u.test(at)), 'neither a test\'s fixture nor a node_modules\' read')
  assert.ok(reads.includes(`/repos/org/repo/contents/web/yarn.lock?ref=${mergeBase}`) && reads.includes(`/repos/org/repo/contents/web/pnpm-lock.yaml?ref=${head}`))
  assert.ok(asked.includes(`/repos/org/repo/compare/${tip}...${head}?per_page=1`))
  assert.deepEqual([...kept.kept.keys()], [`${tip}...${head}`])

  // Kept by its commits: asked again, only the pull request is.
  asked.length = 0
  assert.deepEqual(await pullDependencies('org/repo', 'token', 5, kept), told)
  assert.deepEqual(asked, ['/repos/org/repo/pulls/5'])
})

test('a pull request\'s lockfiles changed but none new tells each directory\'s none; one changing none, no directory', async t => {
  const bump = fresh()
  github(t, { ...bump, compared: [{ filename: 'package-lock.json', status: 'modified' }],
    files: { [bump.baseAt]: { 'package-lock.json': npmLockfile({ ms: registry('ms', '2.1.2') }) }, [bump.headAt]: { 'package-lock.json': npmLockfile({ ms: registry('ms', '2.1.3') }) } } })
  assert.deepEqual((await pullDependencies('org/repo', 'token', 5, memory())).lockfiles, [{ paths: ['package-lock.json'], added: [], more: 0 }])
  t.mock.restoreAll()
  const asked = github(t, { compared: [{ filename: 'src/a.js', status: 'modified' }] })
  assert.deepEqual((await pullDependencies('org/repo', 'token', 5, memory())).lockfiles, [])
  assert.ok(!asked.some(at => at.includes('/contents/')), 'nothing read')
})

test('one changing as many files as GitHub compares has them listed from its own list, a page at a time; past them, or past the directories read, cut', async t => {
  const many = Array.from({ length: 300 }, (_, at) => ({ filename: `src/f${at}.js`, status: 'added' }))
  const asked = github(t, { compared: many, pullFiles: [...many, { filename: 'package-lock.json', status: 'modified' }] })
  const told = await pullDependencies('org/repo', 'token', 5, memory())
  assert.deepEqual(told.lockfiles.map(dir => dir.paths), [['package-lock.json']])
  assert.equal(told.cut, false)
  assert.deepEqual(asked.filter(at => at.includes('/pulls/5/files')), [1, 2, 3, 4].map(page => `/repos/org/repo/pulls/5/files?per_page=100&page=${page}`))

  t.mock.restoreAll()
  const lockfiles = Array.from({ length: MAX_DIRECTORIES + 1 }, (_, at) => `p${String(at).padStart(2, '0')}/package-lock.json`)
  const directories = fresh()
  github(t, { ...directories, compared: lockfiles.map(filename => ({ filename, status: 'added' })),
    files: { [directories.headAt]: Object.fromEntries(lockfiles.map(path => [path, npmLockfile({ ms: registry('ms', '2.1.3') })])) } })
  const cut = await pullDependencies('org/repo', 'token', 5, memory())
  assert.equal(cut.cut, true)
  assert.equal(cut.lockfiles.length, MAX_DIRECTORIES)
})

test('of a lockfile adding more than are told, the first by name, the rest counted', async t => {
  const packages = Object.fromEntries(Array.from({ length: MAX_ADDED + 3 }, (_, at) => `pkg-${String(at).padStart(3, '0')}`).map(name => [name, registry(name, '1.0.0')]))
  const added = fresh()
  github(t, { ...added, compared: [{ filename: 'package-lock.json', status: 'added' }], files: { [added.headAt]: { 'package-lock.json': npmLockfile(packages) } } })
  const [dir] = (await pullDependencies('org/repo', 'token', 5, memory())).lockfiles
  assert.equal(dir.added.length, MAX_ADDED)
  assert.equal(dir.more, 3)
  assert.equal(dir.added[0].name, 'pkg-000')
})

test('GitHub naming another pull request, or failing, is the answer\'s failure, nothing kept', async t => {
  t.mock.method(globalThis, 'fetch', () => Promise.resolve(Response.json({ number: 6, base: { sha: tip, repo: { full_name: 'org/repo' } }, head: { sha: head } })))
  await assert.rejects(pullDependencies('org/repo', 'token', 5, memory()), /github-malformed/u)
  t.mock.restoreAll()
  t.mock.method(globalThis, 'fetch', input => {
    const { pathname } = new URL(typeof input === 'string' ? input : input.url)
    if (pathname === '/repos/org/repo/pulls/5') return Promise.resolve(Response.json({ number: 5, base: { sha: tip, repo: { full_name: 'org/repo' } }, head: { sha: head } }))
    return Promise.resolve(Response.json({ message: 'API rate limit exceeded' }, { status: 403, headers: { 'x-ratelimit-remaining': '0' } }))
  })
  const kept = memory()
  await assert.rejects(pullDependencies('org/repo', 'token', 5, kept), /github-rate-limited/u)
  assert.equal(kept.kept.size, 0)
})

async function fixture(t) {
  const db = openSqliteManagedDb(':memory:')
  t.after(() => db.close())
  const session = await createSession(config, db, { githubUserId: 1, login: 'manager', name: null, avatarUrl: null }, Date.now())
  await db.setUserRole(session.userId, 'admin')
  await db.setUserTokens(session.userId, { accessToken: 'token', refreshToken: null, expiresAt: null })
  await db.selectRepo(repo, Date.now())
  const handler = createManagedRequestHandler({ config, db, originGate: { isOriginAllowed: () => true }, isShuttingDown: () => false, track() {} })
  return async (route, query) => {
    const res = { status: 0, body: '', writeHead(status) { this.status = status }, end(body) { this.body = body } }
    await handler({ method: 'GET', url: `/api/admin/repositories/${route}?${new URLSearchParams(query)}`, headers: { cookie: session.setCookie.split(';')[0] } }, res)
    return { status: res.status, body: JSON.parse(res.body) }
  }
}

test('GET pull-dependencies answers a pull request\'s new packages by its number, read as its popup\'s item is', async t => {
  const request = await fixture(t)
  const asked = github(t)
  const answer = await request('pull-dependencies', { repoId: '1', number: '5' })
  assert.equal(answer.status, 200)
  assert.equal(answer.body.number, 5)
  assert.equal(answer.body.base, mergeBase)
  assert.deepEqual(answer.body.lockfiles.map(dir => dir.paths[0]), ['package-lock.json', 'berry/yarn.lock', 'gone/package-lock.json', 'new/package-lock.json', 'web/pnpm-lock.yaml'])
  asked.length = 0
  assert.deepEqual((await request('pull-dependencies', { repoId: '1', number: '5' })).body, answer.body)
  assert.deepEqual(asked, [], 'kept by its number a while')
  for (const query of [{ repoId: '1', number: '0' }, { repoId: '1', number: '05' }, { repoId: '1', number: String(2 ** 31) }, { repoId: 'x', number: '5' }]) {
    assert.equal((await request('pull-dependencies', query)).status, 400, JSON.stringify(query))
  }
})

test('an open pull request\'s tile, and any one\'s popup, tell whether it changes a lockfile, by the files GitHub lists of it', async t => {
  const request = await fixture(t)
  const queries = []
  const node = (number, paths, total = paths.length) => ({ number, title: `Pull ${number}`, state: 'OPEN', comments: { totalCount: 0 }, labels: { totalCount: 0, nodes: [] },
    files: { totalCount: total, nodes: paths.map(path => ({ path })) } })
  t.mock.method(globalThis, 'fetch', (input, init) => {
    const url = new URL(typeof input === 'string' ? input : input.url)
    if (url.pathname === '/repos/org/repo') return Promise.resolve(Response.json(publicMetadata))
    const { query } = JSON.parse(init.body)
    queries.push(query)
    if (query.includes('issueOrPullRequest')) {
      return Promise.resolve(Response.json({ data: { repository: { item: { __typename: 'PullRequest', ...node(9, ['web/yarn.lock']), pullState: 'MERGED' } } } }))
    }
    return Promise.resolve(Response.json({ data: { repository: { open: { totalCount: 3 }, closed: { totalCount: 0 }, page: { pageInfo: { hasNextPage: false },
      nodes: [node(1, ['src/a.js', 'pnpm-lock.yaml']), node(2, ['src/a.js']), node(3, ['src/a.js'], 250)] } } } }))
  })
  const open = await request('issues', { repoId: '1', kind: 'pulls', state: 'open' })
  assert.deepEqual(open.body.items.map(item => item.touchesLockfile), [true, false, null])
  const closed = await request('issues', { repoId: '1', kind: 'pulls', state: 'closed' })
  assert.match(queries[0], /files\(first: 100\)/u)
  assert.doesNotMatch(queries[1], /files\(/u, 'a closed one\'s tile tells none')
  assert.equal(closed.status, 200)
  const item = await request('item', { repoId: '1', number: '9' })
  assert.equal(item.body.state, 'merged')
  assert.equal(item.body.touchesLockfile, true, 'merged, its popup tells it')
})
